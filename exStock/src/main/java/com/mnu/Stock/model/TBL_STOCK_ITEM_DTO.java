package com.mnu.Stock.model;

public class TBL_STOCK_ITEM_DTO {
	private String stock_item_code;
	private String stock_item_name;
	private String stock_item_market;
	private String stock_item_category;
	private String stock_item_listed_date;
	public String getStock_item_code() {
		return stock_item_code;
	}
	public void setStock_item_code(String stock_item_code) {
		this.stock_item_code = stock_item_code;
	}
	public String getStock_item_name() {
		return stock_item_name;
	}
	public void setStock_item_name(String stock_item_name) {
		this.stock_item_name = stock_item_name;
	}
	public String getStock_item_market() {
		return stock_item_market;
	}
	public void setStock_item_market(String stock_item_market) {
		this.stock_item_market = stock_item_market;
	}
	public String getStock_item_category() {
		return stock_item_category;
	}
	public void setStock_item_category(String stock_item_category) {
		this.stock_item_category = stock_item_category;
	}
	public String getStock_item_listed_date() {
		return stock_item_listed_date;
	}
	public void setStock_item_listed_date(String stock_item_listed_date) {
		this.stock_item_listed_date = stock_item_listed_date;
	}
	

}
