package com.mnu.product.model;

public class tbl_productDTO {
	private String p_code;
	private String p_name;
	private String p_size;
	private String p_incost;
	private String p_outcost;
	private String profit;
	public String getP_code() {
		return p_code;
	}
	public void setP_code(String p_code) {
		this.p_code = p_code;
	}
	public String getP_name() {
		return p_name;
	}
	public void setP_name(String p_name) {
		this.p_name = p_name;
	}
	public String getP_size() {
		return p_size;
	}
	public void setP_size(String p_size) {
		this.p_size = p_size;
	}
	public String getP_incost() {
		return p_incost;
	}
	public void setP_incost(String p_incost) {
		this.p_incost = p_incost;
	}
	public String getP_outcost() {
		return p_outcost;
	}
	public void setP_outcost(String p_outcost) {
		this.p_outcost = p_outcost;
	}
	public String getProfit() {
		return profit;
	}
	public void setProfit(String profit) {
		this.profit = profit;
	}

}
